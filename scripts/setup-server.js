const fs = require('fs');
const path = require('path');
const os = require('os');
const readline = require('readline');
const { execSync } = require('child_process');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const ENV_PATH = path.join(PROJECT_ROOT, '.env');
const INIT_SQL_PATH = path.join(PROJECT_ROOT, 'backend', 'database', 'mssql_init_FRM_DB.sql');

function loadModule(pkgName, fallbackRelative) {
  try {
    return require(pkgName);
  } catch (err) {
    return require(path.join(PROJECT_ROOT, fallbackRelative));
  }
}

const dotenv = loadModule('dotenv', 'node_modules/dotenv');
const sql = loadModule('mssql', 'backend/node_modules/mssql');
const migratorPath = path.join(PROJECT_ROOT, 'backend', 'database', 'migrator.js');
const { runMssqlMigrations } = fs.existsSync(migratorPath)
  ? require(migratorPath)
  : require(path.join(PROJECT_ROOT, 'backend', 'server.js'));
const { generateLocalCert } = require(path.join(PROJECT_ROOT, 'scripts', 'generate-cert'));

function createPrompt() {
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
  });

  const ask = (question, defaultVal = '') => {
    const suffix = defaultVal !== '' ? ` [${defaultVal}]` : '';
    return new Promise((resolve) => {
      rl.question(`${question}${suffix}: `, (answer) => {
        const trimmed = answer.trim();
        resolve(trimmed !== '' ? trimmed : defaultVal);
      });
    });
  };

  const askYesNo = async (question, defaultYes = true) => {
    const hint = defaultYes ? 'Y/n' : 'y/N';
    const ans = await ask(`${question} (${hint})`, defaultYes ? 'Y' : 'n');
    return /^y(es)?$/i.test(ans);
  };

  const close = () => rl.close();
  return { ask, askYesNo, close };
}

function formatEnvValue(val) {
  const str = String(val ?? '');
  if (str === '') return '';
  if (/[\s#"\\]/.test(str)) {
    return `"${str.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
  }
  return str;
}

function readExistingEnv() {
  if (!fs.existsSync(ENV_PATH)) return {};
  try {
    return dotenv.parse(fs.readFileSync(ENV_PATH, 'utf8'));
  } catch (err) {
    console.warn('[Setup] Could not parse existing .env:', err.message);
    return {};
  }
}

function writeEnvFile(cfg) {
  const lines = [
    '# FRM Server Configuration (Generated by setup-server.js)',
    `DB_TYPE=mssql`,
    `DB_SERVER=${formatEnvValue(cfg.dbServer)}`,
    `DB_PORT=${formatEnvValue(cfg.dbPort)}`,
    `DB_NAME=${formatEnvValue(cfg.dbName)}`,
    `DB_USER=${formatEnvValue(cfg.dbUser)}`,
    `DB_PASSWORD=${formatEnvValue(cfg.dbPassword)}`,
    `DB_ENCRYPT=${cfg.dbEncrypt ? 'true' : 'false'}`,
    `DB_TRUST_SERVER_CERTIFICATE=true`,
    '',
    `PORT=${formatEnvValue(cfg.port)}`,
    `HTTPS_PORT=${formatEnvValue(cfg.httpsPort)}`,
    '',
    '# SQLite fallback path if DB_TYPE=sqlite',
    `SQLITE_DB_PATH=backend/database/FRM-BBP.db`
  ];

  if (cfg.emailUser) {
    lines.push('', `EMAIL_USER=${formatEnvValue(cfg.emailUser)}`);
  }
  if (cfg.emailPass) {
    lines.push(`EMAIL_PASS=${formatEnvValue(cfg.emailPass)}`);
  }

  fs.writeFileSync(ENV_PATH, lines.join('\n') + '\n', 'utf8');
}

function printSqlTroubleshooting(err) {
  const msg = String(err && err.message ? err.message : '');
  console.error('\n[ERROR] Could not connect to Microsoft SQL Server 2022 Express.');
  console.error(`Details: ${msg}\n`);

  if (err.code === 'ESOCKET' || /Could not connect|ECONNREFUSED|ETIMEDOUT/i.test(msg)) {
    console.error('How to fix TCP/IP connection (Port 1433):');
    console.error('  1. Open "SQL Server 2022 Configuration Manager".');
    console.error('  2. Expand "SQL Server Network Configuration" -> "Protocols for SQLEXPRESS".');
    console.error('  3. Right-click "TCP/IP" -> Enable.');
    console.error('  4. Double-click "TCP/IP" -> "IP Addresses" tab -> scroll down to "IPAll":');
    console.error('       - Clear "TCP Dynamic Ports" (leave it blank)');
    console.error('       - Set "TCP Port" to: 1433');
    console.error('  5. Go to "SQL Server Services" -> Restart "SQL Server (SQLEXPRESS)".\n');
  } else if (err.code === 'ELOGIN' || /Login failed/i.test(msg)) {
    console.error('How to fix SQL Login (Mixed Mode Authentication):');
    console.error('  1. Open SSMS and connect using Windows Authentication.');
    console.error('  2. Right-click the Server -> Properties -> Security:');
    console.error('       - Select "SQL Server and Windows Authentication mode".');
    console.error('  3. Expand Security -> Logins -> double-click "sa":');
    console.error('       - Set your password, go to "Status" tab -> select Login: Enabled.');
    console.error('  4. Right-click Server -> Restart, then re-run Setup-Server.bat.\n');
  }
}

async function setupDatabase(cfg, prompt) {
  if (!/^[A-Za-z0-9_]+$/.test(cfg.dbName)) {
    throw new Error('Database name must contain only letters, numbers, and underscores.');
  }

  const baseConfig = {
    user: cfg.dbUser,
    password: cfg.dbPassword,
    server: cfg.dbServer,
    port: parseInt(cfg.dbPort, 10),
    requestTimeout: 60000,
    options: {
      encrypt: cfg.dbEncrypt,
      trustServerCertificate: true,
      enableArithAbort: true
    }
  };

  console.log(`\n[*] Testing connection to SQL Server (${cfg.dbServer}:${cfg.dbPort})...`);
  let masterPool;
  try {
    masterPool = await new sql.ConnectionPool({ ...baseConfig, database: 'master' }).connect();
    console.log('[OK] Connected to SQL Server successfully.');
  } catch (err) {
    printSqlTroubleshooting(err);
    throw err;
  }

  try {
    const dbCheck = await masterPool.request()
      .input('DbName', sql.NVarChar(128), cfg.dbName)
      .query('SELECT database_id FROM sys.databases WHERE name = @DbName');

    if (dbCheck.recordset.length === 0) {
      console.log(`[*] Creating database [${cfg.dbName}]...`);
      await masterPool.request().query(`CREATE DATABASE [${cfg.dbName}]`);
      console.log(`[OK] Database [${cfg.dbName}] created.`);
    } else {
      console.log(`[OK] Database [${cfg.dbName}] already exists.`);
    }
  } finally {
    await masterPool.close();
  }

  const dbPool = await new sql.ConnectionPool({ ...baseConfig, database: cfg.dbName }).connect();
  try {
    const tableRes = await dbPool.request().query('SELECT COUNT(*) AS cnt FROM sys.tables WHERE is_ms_shipped = 0');
    const tableCount = tableRes.recordset[0]?.cnt || 0;

    if (tableCount === 0) {
      if (fs.existsSync(INIT_SQL_PATH)) {
        const shouldInit = await prompt.askYesNo(
          `Database [${cfg.dbName}] is empty. Initialize schema & starter data now?`,
          true
        );
        if (shouldInit) {
          console.log('[*] Initializing schema and starter data from mssql_init_FRM_DB.sql...');
          let initSql = fs.readFileSync(INIT_SQL_PATH, 'utf8');
          if (cfg.dbName !== 'FRM_DB') {
            initSql = initSql.replace(/^\s*USE\s+\[FRM_DB\]\s*;?/gmi, `USE [${cfg.dbName}];`);
          }
          const batches = initSql
            .split(/^\s*GO\s*;?\s*$/gmi)
            .map((b) => b.trim())
            .filter((b) => b.length > 0);

          for (let i = 0; i < batches.length; i++) {
            await dbPool.request().query(batches[i]);
          }
          console.log(`[OK] Executed ${batches.length} SQL initialization batches successfully.`);
        } else {
          console.log('[*] Skipped schema initialization (you can restore a .bak file into FRM_DB via SSMS).');
        }
      }
    } else {
      console.log(`[OK] Database [${cfg.dbName}] already has ${tableCount} tables. Preserving existing data.`);
    }

    // Apply any pending incremental migrations safely if tables exist
    const afterTableRes = await dbPool.request().query('SELECT COUNT(*) AS cnt FROM sys.tables WHERE is_ms_shipped = 0');
    if ((afterTableRes.recordset[0]?.cnt || 0) > 0) {
      console.log('[*] Checking pending database migrations...');
      await runMssqlMigrations(dbPool, sql);
      console.log('[OK] Database schema is up to date.');
    }
  } finally {
    await dbPool.close();
  }
}

function getLanUrls(port, httpsPort) {
  const urls = [];
  const nets = os.networkInterfaces();
  for (const name of Object.keys(nets)) {
    for (const net of nets[name]) {
      if (net.family === 'IPv4' && !net.internal && !net.address.startsWith('169.254')) {
        urls.push({
          iface: name,
          http: `http://${net.address}:${port}`,
          https: `https://${net.address}:${httpsPort}`
        });
      }
    }
  }
  return urls;
}

async function main() {
  console.log('=====================================================================');
  console.log('              FRM SERVER MACHINE INTERACTIVE SETUP                   ');
  console.log('=====================================================================\n');

  const prompt = createPrompt();
  try {
    const existing = readExistingEnv();

    console.log('Step 1: Database & Server Settings (Press Enter to keep [default])');
    const dbServer = await prompt.ask('  SQL Server Host', existing.DB_SERVER || 'localhost');
    const dbPort = await prompt.ask('  SQL Server Port', existing.DB_PORT || '1433');
    const dbName = await prompt.ask('  Database Name', existing.DB_NAME || 'FRM_DB');
    const dbUser = await prompt.ask('  SQL Login Username', existing.DB_USER || 'sa');

    let dbPassword = '';
    while (!dbPassword) {
      const hint = existing.DB_PASSWORD ? 'leave empty to keep existing' : 'required';
      const entered = await prompt.ask(`  SQL Password (${hint})`, '');
      if (entered) {
        dbPassword = entered;
      } else if (existing.DB_PASSWORD) {
        dbPassword = existing.DB_PASSWORD;
      } else {
        console.log('  [!] Password is required to connect with SQL Authentication.');
      }
    }

    const port = await prompt.ask('  Web App HTTP Port', existing.PORT || '5000');
    const httpsPort = await prompt.ask('  Web App HTTPS Port (for Mobile PWA)', existing.HTTPS_PORT || '5443');
    const emailUser = await prompt.ask('  Activation Email Sender (optional)', existing.EMAIL_USER || '');
    let emailPass = existing.EMAIL_PASS || '';
    if (emailUser) {
      const enteredPass = await prompt.ask(
        `  Activation Email App Password (${existing.EMAIL_PASS ? 'leave empty to keep existing' : 'optional'})`,
        ''
      );
      if (enteredPass) emailPass = enteredPass;
    }

    const cfg = {
      dbServer,
      dbPort,
      dbName,
      dbUser,
      dbPassword,
      dbEncrypt: existing.DB_ENCRYPT === 'true',
      port,
      httpsPort,
      emailUser,
      emailPass
    };

    writeEnvFile(cfg);
    console.log(`\n[OK] Saved configuration to ${ENV_PATH}`);

    console.log('\nStep 2: Database Connection & Schema Setup');
    await setupDatabase(cfg, prompt);

    console.log('\nStep 3: Generating HTTPS SSL Certificate for this Server IP');
    try {
      await generateLocalCert();
    } catch (certErr) {
      console.warn('[WARN] Could not generate SSL certificates:', certErr.message);
      console.warn('       HTTP access on port ' + port + ' will still work normally.');
    }

    console.log('\nStep 4: Frontend Web Assets Check');
    const frontendPkg = path.join(PROJECT_ROOT, 'frontend', 'package.json');
    const prebuiltIndex = path.join(PROJECT_ROOT, 'public', 'index.html');
    if (fs.existsSync(frontendPkg)) {
      execSync('npm --prefix frontend run build', {
        cwd: PROJECT_ROOT,
        stdio: 'inherit',
        shell: true
      });
      console.log('[OK] Frontend production build completed.');
    } else if (fs.existsSync(prebuiltIndex)) {
      console.log('[OK] Pre-built frontend assets found in public/ (skipping build).');
    } else {
      throw new Error('Frontend assets missing: neither frontend/ nor public/index.html was found.');
    }

    console.log('\nStep 5: Windows Shortcuts & Boot Auto-Start');
    if (await prompt.askYesNo('Create Desktop Shortcut ("FRM-BBP")?', true)) {
      execSync('node scripts/create-desktop-shortcut.js', { cwd: PROJECT_ROOT, stdio: 'inherit', shell: true });
    }
    if (await prompt.askYesNo('Enable Auto-Start when Server PC boots & logs in?', true)) {
      execSync('node scripts/enable-autostart.js', { cwd: PROJECT_ROOT, stdio: 'inherit', shell: true });
    }

    const lanUrls = getLanUrls(port, httpsPort);
    console.log('\n=====================================================================');
    console.log('                 FRM SERVER SETUP COMPLETED!                         ');
    console.log('=====================================================================');
    console.log('To start the server right now, double-click: Start-FRM.bat\n');
    console.log('Access URLs once running:');
    console.log(`  - On this Server PC:            http://localhost:${port}`);
    if (lanUrls.length > 0) {
      for (const u of lanUrls) {
        console.log(`  - On Office PCs/Mobiles (${u.iface}):`);
        console.log(`      HTTP : ${u.http}`);
        console.log(`      HTTPS: ${u.https}  (for Mobile PWA Install)`);
      }
    } else {
      console.log(`  - On other devices: http://<SERVER-LAN-IP>:${port}`);
    }
    console.log('\nNote: Default admin login (for fresh DB): admin / admin123');
    console.log('=====================================================================\n');
  } finally {
    prompt.close();
  }
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error('\n[Setup Failed]:', err && err.message ? err.message : err);
    process.exit(1);
  });

